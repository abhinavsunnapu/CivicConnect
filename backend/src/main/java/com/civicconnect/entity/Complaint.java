package com.civicconnect.entity;

import com.civicconnect.entity.enums.ComplaintCategory;
import com.civicconnect.entity.enums.ComplaintPriority;
import com.civicconnect.entity.enums.ComplaintStatus;
import com.fasterxml.jackson.annotation.JsonIgnore;
import jakarta.persistence.CascadeType;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.ForeignKey;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.OneToMany;
import jakarta.persistence.OrderBy;
import jakarta.persistence.Table;
import jakarta.persistence.Version;
import jakarta.validation.constraints.DecimalMax;
import jakarta.validation.constraints.DecimalMin;
import jakarta.validation.constraints.Digits;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Size;
import java.math.BigDecimal;
import java.time.Instant;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import org.hibernate.annotations.Generated;

/**
 * A civic issue reported by a citizen.
 * <p>
 * Images, status history and assignments belong to the complaint: they are saved and deleted with it.
 * All associations are lazy and hidden from JSON; the API returns DTOs, never entities.
 */
@Entity
@Table(name = "complaints")
public class Complaint extends BaseEntity {

    /** Human-friendly reference such as {@code CC-2026-000042}, generated by the database on insert. */
    @Generated
    @Column(name = "reference_number", nullable = false, unique = true, length = 20,
            insertable = false, updatable = false)
    private String referenceNumber;

    @JsonIgnore
    @NotNull
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "reporter_id", nullable = false, foreignKey = @ForeignKey(name = "fk_complaints_reporter"))
    private User reporter;

    /** Department the complaint is currently routed to; {@code null} until routed. */
    @JsonIgnore
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "department_id", foreignKey = @ForeignKey(name = "fk_complaints_department"))
    private Department department;

    @NotBlank
    @Size(max = 200)
    @Column(name = "title", nullable = false, length = 200)
    private String title;

    @NotBlank
    @Column(name = "description", nullable = false, columnDefinition = "text")
    private String description;

    @NotNull
    @Enumerated(EnumType.STRING)
    @Column(name = "category", nullable = false, length = 30)
    private ComplaintCategory category;

    @NotNull
    @Enumerated(EnumType.STRING)
    @Column(name = "status", nullable = false, length = 30)
    private ComplaintStatus status = ComplaintStatus.SUBMITTED;

    @NotNull
    @Enumerated(EnumType.STRING)
    @Column(name = "priority", nullable = false, length = 20)
    private ComplaintPriority priority = ComplaintPriority.MEDIUM;

    @NotNull
    @DecimalMin("-90.0")
    @DecimalMax("90.0")
    @Digits(integer = 3, fraction = 6)
    @Column(name = "latitude", nullable = false, precision = 9, scale = 6)
    private BigDecimal latitude;

    @NotNull
    @DecimalMin("-180.0")
    @DecimalMax("180.0")
    @Digits(integer = 3, fraction = 6)
    @Column(name = "longitude", nullable = false, precision = 9, scale = 6)
    private BigDecimal longitude;

    @Size(max = 500)
    @Column(name = "address", length = 500)
    private String address;

    @Column(name = "resolved_at")
    private Instant resolvedAt;

    /** Optimistic locking: concurrent updates to the same complaint fail instead of overwriting each other. */
    @Version
    @Column(name = "version", nullable = false)
    private long version;

    @JsonIgnore
    @OneToMany(mappedBy = "complaint", cascade = CascadeType.ALL, orphanRemoval = true)
    @OrderBy("createdAt ASC")
    private List<ComplaintImage> images = new ArrayList<>();

    @JsonIgnore
    @OneToMany(mappedBy = "complaint", cascade = CascadeType.ALL, orphanRemoval = true)
    @OrderBy("createdAt ASC")
    private List<ComplaintStatusHistory> statusHistory = new ArrayList<>();

    @JsonIgnore
    @OneToMany(mappedBy = "complaint", cascade = CascadeType.ALL, orphanRemoval = true)
    @OrderBy("createdAt ASC")
    private List<ComplaintAssignment> assignments = new ArrayList<>();

    protected Complaint() {
        // Required by JPA
    }

    public Complaint(User reporter, String title, String description, ComplaintCategory category,
                     BigDecimal latitude, BigDecimal longitude) {
        this.reporter = reporter;
        this.title = title;
        this.description = description;
        this.category = category;
        this.latitude = latitude;
        this.longitude = longitude;
    }

    // ----- Relationship helpers: keep both sides of each association in sync -----

    public void addImage(ComplaintImage image) {
        images.add(image);
        image.setComplaint(this);
    }

    public void removeImage(ComplaintImage image) {
        images.remove(image);
        image.setComplaint(null);
    }

    public void addStatusHistory(ComplaintStatusHistory entry) {
        statusHistory.add(entry);
        entry.setComplaint(this);
    }

    public void addAssignment(ComplaintAssignment assignment) {
        assignments.add(assignment);
        assignment.setComplaint(this);
    }

    // ----- Getters and setters -----

    public String getReferenceNumber() {
        return referenceNumber;
    }

    public User getReporter() {
        return reporter;
    }

    public void setReporter(User reporter) {
        this.reporter = reporter;
    }

    public Department getDepartment() {
        return department;
    }

    public void setDepartment(Department department) {
        this.department = department;
    }

    public String getTitle() {
        return title;
    }

    public void setTitle(String title) {
        this.title = title;
    }

    public String getDescription() {
        return description;
    }

    public void setDescription(String description) {
        this.description = description;
    }

    public ComplaintCategory getCategory() {
        return category;
    }

    public void setCategory(ComplaintCategory category) {
        this.category = category;
    }

    public ComplaintStatus getStatus() {
        return status;
    }

    public void setStatus(ComplaintStatus status) {
        this.status = status;
    }

    public ComplaintPriority getPriority() {
        return priority;
    }

    public void setPriority(ComplaintPriority priority) {
        this.priority = priority;
    }

    public BigDecimal getLatitude() {
        return latitude;
    }

    public void setLatitude(BigDecimal latitude) {
        this.latitude = latitude;
    }

    public BigDecimal getLongitude() {
        return longitude;
    }

    public void setLongitude(BigDecimal longitude) {
        this.longitude = longitude;
    }

    public String getAddress() {
        return address;
    }

    public void setAddress(String address) {
        this.address = address;
    }

    public Instant getResolvedAt() {
        return resolvedAt;
    }

    public void setResolvedAt(Instant resolvedAt) {
        this.resolvedAt = resolvedAt;
    }

    public long getVersion() {
        return version;
    }

    public List<ComplaintImage> getImages() {
        return Collections.unmodifiableList(images);
    }

    public List<ComplaintStatusHistory> getStatusHistory() {
        return Collections.unmodifiableList(statusHistory);
    }

    public List<ComplaintAssignment> getAssignments() {
        return Collections.unmodifiableList(assignments);
    }
}
